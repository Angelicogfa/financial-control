def test_data_from_the_model_itself_calibrate() -> None:
    rng = np.random.default_rng(8)
    sample = _sample(
        {A: np.expm1(rng.normal(0.002, 0.06, 300)), RE: np.expm1(rng.normal(0.001, 0.035, 300))}
    )
    result = calibrate(sample, {A: 0.4, RE: 0.3, CX: 0.3}, seed=1)
    assert result.windows == 300 - 60 - 12 + 1
    assert result.effective_windows == pytest.approx(result.windows / 12, abs=0.01)
    assert sum(result.weights.values()) == pytest.approx(1.0, abs=1e-3)
    by_key = {g.key: g for g in result.generators}
    assert set(by_key) == {"BOOTSTRAP", "BAYESIAN_BOOTSTRAP", "BAYESIAN_NORMAL", "STACKED"}
    for g in result.generators:
        assert g.status != CalibrationStatus.MISCALIBRATED
        assert g.coverage_low <= 0.90 <= g.coverage_high
        assert sum(g.pit_histogram) == result.windows
    assert len(result.origins) == result.windows
    assert set(result.origins[0].forecasts) == set(by_key)


def test_a_volatility_jump_is_flagged_as_miscalibrated() -> None:
    rng = np.random.default_rng(9)
    calm = rng.normal(0.0, 0.01, 200)
    wild = rng.normal(0.0, 0.12, 200)
    sample = _sample({A: np.expm1(np.concatenate([calm, wild]))})
    result = calibrate(sample, {A: 1.0}, seed=1, min_train=150)
    bootstrap = next(g for g in result.generators if g.key == "BOOTSTRAP")
    assert bootstrap.coverage < 0.7
    assert bootstrap.status == CalibrationStatus.MISCALIBRATED
    assert any("mal calibrado" in w for w in result.warnings)


def test_calibration_uses_only_the_data_before_each_origin() -> None:
    rng = np.random.default_rng(10)
    values = np.expm1(rng.normal(0.002, 0.05, 120))
    changed = values.copy()
    changed[100:] = 0.5  # the future after the first origins changes completely
    a = calibrate(_sample({A: values}), {A: 1.0}, seed=1)
    b = calibrate(_sample({A: changed}), {A: 1.0}, seed=1)
    first_a, first_b = a.origins[0].forecasts, b.origins[0].forecasts
    # Origin 60 only saw months 0..59: every generator forecasts the same.
    for g in Generator:
        assert first_a[g.value] == first_b[g.value]
    # The stacking weights are fitted over all origins, so only the mixture moves.
    assert a.weights != b.weights
    with pytest.raises(InsufficientHistory):
        calibrate(_sample({A: values[:70]}), {A: 1.0}, seed=1)


def test_short_history_is_inconclusive() -> None:
    rng = np.random.default_rng(11)
    sample = _sample({A: np.expm1(rng.normal(0.002, 0.05, 100))})
    result = calibrate(sample, {A: 1.0}, seed=1)
    assert result.effective_windows < 8
    assert all(g.status == CalibrationStatus.INCONCLUSIVE for g in result.generators)
    assert any("inconclusiva" in w for w in result.warnings)


# --- worker, routes and MCP ----------------------------------------------------------------------

TODAY = date.today()
PROJECTION = {
    "horizon_years": 3,
    "monthly_contribution": 1000.0,
    "initial_by_class": {"ACOES": 10_000.0, "CAIXA": 5000.0},
    "cdi_rate": 0.10,
    "ipca_rate": 0.04,
    "wealth_goal": 40_000.0,
    "paths": 300,
}


def _seed(api: SimpleNamespace, years: int = 9) -> None:
    days, day = [], TODAY - timedelta(days=years * 365)
    while day <= TODAY:
        if day.weekday() < 5:
            days.append(day)
        day += timedelta(days=1)
    rng = np.random.default_rng(12)
    level, ibov = 100_000.0, []
    for d in days:
        level *= 1.0 + float(rng.normal(0.0004, 0.012))
        ibov.append((d, level))
    targets = {A: 60.0, CX: 40.0}
    with api.uow_factory() as uow:
        uow.market_series.upsert_points(index_symbol("IBOV"), ibov, unit=SeriesUnit.INDEX_POINTS)
        uow.market_series.upsert_points(
            "CDI", [(d, 0.04) for d in days], unit=SeriesUnit.PERCENT_PER_DAY
        )
        uow.policies.add(
            InvestmentPolicy(
                arca=ArcaPolicy({c: ClassPolicy(target_pct=targets.get(c, 0.0)) for c in ArcaClass})
            )
        )
        uow.commit()


def test_calibration_runs_in_the_worker_and_feeds_the_projection(api: SimpleNamespace) -> None:
    _seed(api)
    empty = api.client.get("/api/v1/simulations/calibration").json()
    assert empty["run_id"] is None and empty["generators"] == []

    # Before any calibration, the projection mixes the generators with equal weights.
    first = api.client.post("/api/v1/simulations/projections", json=PROJECTION).json()
    run_pending_simulations_job(api.uow_factory, timeout_seconds=60)
    before = api.client.get(f"/api/v1/simulations/{first['id']}/projection").json()
    assert before["calibration_run"] is None
    assert any("Ainda não há calibração" in w for w in before["warnings"])
    base = before["scenarios"][1]
    assert sum(g["paths"] for g in base["generators"]) == 300
    assert {g["key"] for g in base["generators"]} == {g.value for g in Generator}
    goal = base["wealth_goal"]
    assert goal["low"] <= goal["probability"] <= goal["high"]
    assert [e["key"] for e in base["events"]] == ["LOSS_10_12M", "BEAT_CDI"]
    acoes = next(p for p in base["premises"] if p["arca_class"] == "ACOES")
    assert acoes["prior_excess_annual"] == pytest.approx(0.03)
    assert acoes["posterior_excess_annual"] is not None
    assert base["prior_months"] is not None

    queued = api.client.post("/api/v1/simulations/calibrations")
    assert queued.status_code == 202 and queued.json()["kind"] == "CALIBRATION"
    again = api.client.post("/api/v1/simulations/calibrations").json()
    assert again["id"] == queued.json()["id"]  # one waiting request, not two
    waiting = api.client.get("/api/v1/simulations/calibration").json()
    assert waiting["pending_run_id"] == queued.json()["id"]

    assert run_pending_simulations_job(api.uow_factory, timeout_seconds=120) == {"DONE": 1}
    data = api.client.get("/api/v1/simulations/calibration").json()
    assert data["run_id"] == queued.json()["id"] and data["status"] == "DONE"
    assert data["classes"] == ["ACOES", "CAIXA"] and data["windows"] > 0
    assert {g["key"] for g in data["generators"]} >= {"BOOTSTRAP", "STACKED"}
    assert sum(data["weights"].values()) == pytest.approx(1.0, abs=1e-3)
    assert len(data["origins"]) == data["windows"]
    by_id = api.client.get("/api/v1/simulations/calibration", params={"run_id": data["run_id"]})
    assert by_id.json()["weights"] == data["weights"]

    after = api.client.post("/api/v1/simulations/projections", json=PROJECTION).json()
    run_pending_simulations_job(api.uow_factory, timeout_seconds=60)
    projected = api.client.get(f"/api/v1/simulations/{after['id']}/projection").json()
    assert projected["calibration_run"] == data["run_id"]
    shares = {g["key"]: g["weight"] for g in projected["scenarios"][1]["generators"]}
    assert shares == {k: v for k, v in data["weights"].items() if round(v * 300) > 0}


def test_a_single_generator_can_be_chosen(api: SimpleNamespace) -> None:
    _seed(api)
    run = api.client.post(
        "/api/v1/simulations/projections", json={**PROJECTION, "generator": "BAYESIAN_NORMAL"}
    ).json()
    run_pending_simulations_job(api.uow_factory, timeout_seconds=60)
    data = api.client.get(f"/api/v1/simulations/{run['id']}/projection").json()
    generators = data["scenarios"][1]["generators"]
    assert [(g["key"], g["paths"]) for g in generators] == [("BAYESIAN_NORMAL", 300)]
    assert not any("calibração" in w for w in data["warnings"])
    bad = api.client.post("/api/v1/simulations/projections", json={**PROJECTION, "generator": "X"})
    assert bad.status_code == 422


def test_a_short_history_fails_the_calibration(api: SimpleNamespace) -> None:
    _seed(api, years=3)
    api.client.post("/api/v1/simulations/calibrations")
    assert run_pending_simulations_job(api.uow_factory, timeout_seconds=60) == {"FAILED": 1}
    data = api.client.get("/api/v1/simulations/calibration").json()
    assert data["run_id"] is None  # only finished calibrations are read


def test_queue_calibration_and_mcp(api: SimpleNamespace) -> None:
    with api.uow_factory() as uow:
        first = queue_calibration(uow)
        assert queue_calibration(uow).id == first.id
        uow.commit()
    handlers = AgenticRuntimeHandlers(
        uow_factory=api.uow_factory,
        portfolio_service=PortfolioApplicationService(offline_gateway()),
    )
    submit = CATALOG_BY_NAME["simulation.calibrate"]
    assert submit.kind == "command"
    assert submit.invoke(handlers, submit.input_model()).id == first.id
    read = CATALOG_BY_NAME["simulation.calibration"]
    assert read.invoke(handlers, read.input_model()).pending_run_id == first.id
