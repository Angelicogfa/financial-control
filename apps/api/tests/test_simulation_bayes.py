A, RE, CX = ArcaClass.ACOES, ArcaClass.REAL_ESTATE, ArcaClass.CAIXA


def _sample(excess_by_class: dict[ArcaClass, np.ndarray], cdi: float = 0.008) -> ClassSample:
    t = len(next(iter(excess_by_class.values())))
    order = [A, RE, ArcaClass.ATIVOS_INTERNACIONAIS, CX]
    excess = np.zeros((t, 4))
    for cls, values in excess_by_class.items():
        excess[:, order.index(cls)] = values
    months = tuple(date(2004 + i // 12, i % 12 + 1, 28) for i in range(t))
    return ClassSample(
        months=months,
        excess=excess,
        cdi=np.full(t, cdi),
        classes=tuple(c for c in order if c in excess_by_class or c == CX),
    )


# --- conjugate posterior ----------------------------------------------------------------------


def test_without_data_the_posterior_is_the_prior() -> None:
    cov = np.array([[0.004, 0.001], [0.001, 0.002]])
    post = niw_posterior(np.empty((0, 2)), [A, RE], prior_cov=cov, prior_months=60.0)
    assert post.mean == pytest.approx(prior_mean([A, RE]))
    assert post.kappa == 60.0 and post.months == 0
    assert post.expected_covariance == pytest.approx(cov)


def test_with_a_huge_sample_the_posterior_is_the_sample() -> None:
    rng = np.random.default_rng(1)
    cov = np.array([[0.004, 0.001], [0.001, 0.002]])
    x = rng.multivariate_normal([0.006, -0.002], cov, size=200_000)
    post = niw_posterior(x, [A, RE], prior_months=60.0)
    assert post.mean == pytest.approx(x.mean(axis=0), abs=1e-5)
    assert post.expected_covariance == pytest.approx(np.cov(x, rowvar=False), rel=1e-3)


def test_closed_form_matches_a_numerical_integration_of_the_posterior() -> None:
    """1-D case (normal-inverse-gamma): integrate prior x likelihood on a (μ, σ²) grid."""
    rng = np.random.default_rng(2)
    x = rng.normal(0.01, 0.05, size=40)[:, None]
    prior_var, kappa0 = 0.0025, 12.0
    post = niw_posterior(x, [A], prior_cov=np.array([[prior_var]]), prior_months=kappa0)

    mu0, nu0 = float(post.prior_mean[0]), 3.0  # ν0 = K + 2
    psi0 = prior_var * (nu0 - 2.0)  # E[σ²] = Ψ0 / (ν0 - K - 1)
    mus = np.linspace(-0.05, 0.07, 801)
    variances = np.linspace(0.0004, 0.012, 801)
    m, v = np.meshgrid(mus, variances, indexing="ij")
    # IW(ν0, Ψ0) in 1-D is an inverse gamma(ν0 / 2, Ψ0 / 2); μ | σ² ~ N(μ0, σ² / κ0).
    log_prior = (-(nu0 / 2.0 + 1.0) * np.log(v) - psi0 / (2.0 * v)) + (
        -0.5 * np.log(v / kappa0) - kappa0 * (m - mu0) ** 2 / (2.0 * v)
    )
    xs = x[:, 0]
    log_lik = -0.5 * xs.size * np.log(v) - (
        ((xs[None, None, :] - m[..., None]) ** 2).sum(axis=-1) / (2.0 * v)
    )
    weight = np.exp(log_prior + log_lik - (log_prior + log_lik).max())
    weight /= weight.sum()
    assert float((weight * m).sum()) == pytest.approx(float(post.mean[0]), rel=1e-3)
    assert float((weight * v).sum()) == pytest.approx(
        float(post.expected_covariance[0, 0]), rel=2e-2
    )


def test_draws_follow_the_posterior_moments() -> None:
    rng = np.random.default_rng(3)
    x = rng.multivariate_normal([0.004, 0.001], [[0.004, 0.001], [0.001, 0.002]], size=120)
    post = niw_posterior(x, [A, RE])
    mus, covs = sample_parameters(post, 100_000, rng)
    assert mus.mean(axis=0) == pytest.approx(post.mean, abs=2e-4)
    assert covs.mean(axis=0) == pytest.approx(post.expected_covariance, rel=2e-2, abs=2e-5)
    iw = sample_inverse_wishart(10.0, np.eye(2), 100_000, rng)
    assert iw.mean(axis=0) == pytest.approx(np.eye(2) / 7.0, abs=3e-3)


def test_bayes_stein_weight_follows_the_distance_to_the_target() -> None:
    rng = np.random.default_rng(4)
    target = prior_mean([A])
    near = rng.normal(0.0, 0.05, size=(120, 1))
    near += target - near.mean(axis=0)  # sample mean exactly on the target
    assert bayes_stein_weight(near, target) == pytest.approx(1.0)
    assert niw_posterior(near, [A]).prior_months == MAX_PRIOR_MONTHS
    far = rng.normal(0.03, 0.02, size=(240, 1))
    post = niw_posterior(far, [A])
    assert post.prior_months < 10  # the data dominate
    assert bayes_stein_weight(np.zeros((3, 1)), target) == 1.0  # too short to estimate


def test_beta_quantiles_and_credible_interval() -> None:
    assert beta_quantiles(3, 5, [0.05, 0.5, 0.95]) == pytest.approx(
        [0.1288, 0.3641, 0.6587], abs=1e-3
    )
    low, high = credible_interval(740, 1000)
    assert low < 0.74 < high and high - low == pytest.approx(0.045, abs=0.005)
    # Beta(1, 51): closed-form quantiles 1 - (1 - p) ** (1 / 51).
    low, high = credible_interval(0, 50)
    assert low == pytest.approx(1 - 0.95 ** (1 / 51), abs=2e-4)
    assert high == pytest.approx(1 - 0.05 ** (1 / 51), abs=2e-4)


def test_stacking_picks_the_model_that_explains_the_data() -> None:
    rng = np.random.default_rng(5)
    y = rng.normal(0.0, 1.0, 2000)

    def normal_pdf(v: np.ndarray, mu: float, sd: float) -> np.ndarray:
        return np.exp(-0.5 * ((v - mu) / sd) ** 2) / (sd * math.sqrt(2 * math.pi))

    good, bad = normal_pdf(y, 0.0, 1.0), normal_pdf(y, 3.0, 1.0)
    assert stacking_weights(np.column_stack([good, bad]))[0] > 0.99
    # Two halves of a bimodal truth: stacking mixes them.
    z = np.concatenate([rng.normal(-2, 0.5, 1000), rng.normal(2, 0.5, 1000)])
    weights = stacking_weights(np.column_stack([normal_pdf(z, -2, 0.5), normal_pdf(z, 2, 0.5)]))
    assert weights == pytest.approx([0.5, 0.5], abs=0.05)


# --- generators and probabilities ------------------------------------------------------------


def test_bayesian_bootstrap_reweights_the_months_per_path() -> None:
    idx = bayesian_bootstrap_indices(50, 600, 40, 6.0, np.random.default_rng(6))
    assert idx.min() >= 0 and idx.max() < 50
    counts = np.array([np.bincount(row, minlength=50) for row in idx])
    assert not np.allclose(counts[0], counts[1])  # each path has its own weights


def test_generators_and_mixture() -> None:
    rng = np.random.default_rng(7)
    sample = _sample({A: np.expm1(rng.normal(0.003, 0.06, 150))})
    normal = draw_excess(
        sample, Generator.BAYESIAN_NORMAL, 300, 24, mean_block=12.0, rng=np.random.default_rng(1)
    )
    assert normal.shape == (300, 24, 4)
    assert np.all(normal[:, :, 1:] == 0.0)  # only the class with a proxy moves
    assert normal[:, :, 0].std() == pytest.approx(0.06, rel=0.15)

    assert mixture_counts({"A": 0.5, "B": 0.3, "C": 0.2}, 7) == {"A": 4, "B": 2, "C": 1}
    weights = {"BOOTSTRAP": 0.2, "BAYESIAN_BOOTSTRAP": 0.3, "BAYESIAN_NORMAL": 0.5}
    first, labels = draw_mixture(sample, weights, 1000, 12, mean_block=12.0, seed=3)
    again, _ = draw_mixture(sample, weights, 1000, 12, mean_block=12.0, seed=3)
    assert np.array_equal(first, again)
    assert (labels == "BAYESIAN_NORMAL").sum() == 500 and first.shape == (1000, 12, 4)


def test_chance_interval_covers_the_generators() -> None:
    hits = np.array([True] * 600 + [False] * 400 + [True] * 300 + [False] * 700)
    labels = np.array(["A"] * 1000 + ["B"] * 1000)
    c = chance(hits, labels)
    assert c.probability == 0.45
    assert c.by_generator == {"A": 0.6, "B": 0.3}
    assert c.low <= 0.3 and c.high >= 0.6
    plain = chance(hits)
    assert plain.low < 0.45 < plain.high and plain.high - plain.low < 0.05


