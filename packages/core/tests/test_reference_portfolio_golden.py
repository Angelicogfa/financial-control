"""Golden-value tests: consolidation of the reference portfolio vs independent expectations.

Expected values come from `golden/reference_portfolio_expected.csv`, generated by
`golden/build_reference_golden.py` (stdlib only, never imports `fincontrol_core`).
Rows tagged with a `known_finding` are strict xfails until that finding is fixed;
the fix must remove the tag from `KNOWN_FINDINGS` in the generator and rerun it.
"""

from __future__ import annotations

import csv
from pathlib import Path

import pytest
from fincontrol_core.portfolio.consolidation import ConsolidatedPortfolioReport

GOLDEN_CSV = Path(__file__).resolve().parent / "golden" / "reference_portfolio_expected.csv"
TOLERANCE_BRL = 0.01

# Golden metric name -> ValuedAssetPosition attribute (when the names differ).
POSITION_FIELDS = {"gross_value_brl": "gross_current_value_brl"}


def _golden_rows() -> list[pytest.param]:
    with GOLDEN_CSV.open(encoding="utf-8", newline="") as fh:
        rows = list(csv.DictReader(fh))
    params = []
    for row in rows:
        marks = []
        if row["known_finding"]:
            marks.append(
                pytest.mark.xfail(
                    strict=True,
                    raises=AssertionError,
                    reason=f"{row['known_finding']}: known defect in current engine",
                )
            )
        params.append(
            pytest.param(
                row["ticker"],
                row["metric"],
                float(row["expected"]),
                marks=marks,
                id=f"{row['ticker']}-{row['metric']}",
            )
        )
    return params


def _actual(report: ConsolidatedPortfolioReport, ticker: str, metric: str) -> float:
    if ticker == "PORTFOLIO":
        return getattr(report, metric)
    position = next(p for p in report.positions if p.ticker == ticker)
    return getattr(position, POSITION_FIELDS.get(metric, metric))


@pytest.mark.parametrize(("ticker", "metric", "expected"), _golden_rows())
def test_reference_portfolio_matches_golden(
    reference_report: ConsolidatedPortfolioReport,
    ticker: str,
    metric: str,
    expected: float,
) -> None:
    assert _actual(reference_report, ticker, metric) == pytest.approx(expected, abs=TOLERANCE_BRL)


def test_golden_csv_is_in_sync_with_generator() -> None:
    import importlib.util

    spec = importlib.util.spec_from_file_location(
        "build_reference_golden", GOLDEN_CSV.parent / "build_reference_golden.py"
    )
    assert spec is not None and spec.loader is not None
    generator = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(generator)

    import json

    data = json.loads(generator.INPUT.read_text(encoding="utf-8"))
    regenerated = [
        (str(r["ticker"]), str(r["metric"]), str(r["expected"]), str(r["known_finding"]))
        for r in generator.build_rows(data)
    ]
    with GOLDEN_CSV.open(encoding="utf-8", newline="") as fh:
        on_disk = [
            (r["ticker"], r["metric"], r["expected"], r["known_finding"])
            for r in csv.DictReader(fh)
        ]
    assert regenerated == on_disk
