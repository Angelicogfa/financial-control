"""Generate apps/web/src/api/types.ts from the API's OpenAPI schema.

    uv run python scripts/gen_web_types.py

The frontend never re-declares backend shapes by hand: run this after changing a DTO.
"""

from __future__ import annotations

import re
from pathlib import Path
from typing import Any

from fincontrol_api.main import create_app

OUT = Path(__file__).resolve().parents[1] / "apps" / "web" / "src" / "api" / "types.ts"
SKIP = re.compile(r"^(HTTPValidationError|ValidationError|Body_.*)$")


def _name(ref: str) -> str:
    raw = ref.rsplit("/", 1)[-1]
    # PaginatedResponse[AssetResponseDTO] -> PaginatedResponse_AssetResponseDTO_
    return re.sub(r"[^A-Za-z0-9_]", "_", raw)


def ts_type(schema: dict[str, Any]) -> str:
    if "$ref" in schema:
        return _name(schema["$ref"])
    if "enum" in schema:
        return " | ".join(f'"{v}"' for v in schema["enum"])
    if "const" in schema:
        return f'"{schema["const"]}"'
    for key in ("anyOf", "oneOf"):
        if key in schema:
            parts = []
            for option in schema[key]:
                text = ts_type(option)
                if text not in parts:
                    parts.append(text)
            return " | ".join(parts)
    kind = schema.get("type")
    if kind == "array":
        inner = ts_type(schema.get("items", {}))
        return f"({inner})[]" if "|" in inner else f"{inner}[]"
    if kind == "object":
        extra = schema.get("additionalProperties")
        if isinstance(extra, dict) and extra:
            names = schema.get("propertyNames", {})
            key_type = ts_type(names) if names.get("enum") else "string"
            if key_type != "string":
                return f"Partial<Record<{key_type}, {ts_type(extra)}>>"
            return f"Record<string, {ts_type(extra)}>"
        return "Record<string, unknown>"
    if kind in ("integer", "number"):
        return "number"
    if kind == "string":
        # Decimals travel as strings in JSON.
        return "string"
    if kind == "boolean":
        return "boolean"
    if kind == "null":
        return "null"
    return "unknown"


def main() -> None:
    schemas = create_app().openapi()["components"]["schemas"]
    lines = [
        "// Generated by scripts/gen_web_types.py from the API OpenAPI schema. Do not edit.",
        "/* eslint-disable */",
        "",
    ]
    for raw_name in sorted(schemas):
        name = _name(raw_name)
        if SKIP.match(raw_name):
            continue
        schema = schemas[raw_name]
        if "enum" in schema:
            lines.append(f"export type {name} = {ts_type(schema)};")
            lines.append("")
            continue
        required = set(schema.get("required", []))
        lines.append(f"export interface {name} {{")
        for prop, spec in schema.get("properties", {}).items():
            optional = "" if prop in required else "?"
            lines.append(f"  {prop}{optional}: {ts_type(spec)};")
        lines.append("}")
        lines.append("")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"wrote {OUT} ({len(schemas)} schemas)")


if __name__ == "__main__":
    main()
